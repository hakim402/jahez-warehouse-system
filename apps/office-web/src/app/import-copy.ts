export function importCopy(language: 0 | 1 | 2) {
  const localized = (group: Record<string, readonly string[]>) =>
    Object.fromEntries(Object.entries(group).map(([key, values]) => [key, values[language]]));
  return {
    ...localized(labels),
    importField: localized(fieldLabels),
    importKind: localized({ purchase: ['Purchase order', 'أمر شراء', '采购订单'], expense: ['Expense', 'مصروف', '费用'] }),
    importStatus: localized({
      queued: ['Queued', 'في قائمة الانتظار', '排队中'],
      processing: ['Processing', 'قيد المعالجة', '处理中'],
      draft: ['Ready for review', 'جاهز للمراجعة', '待审核'],
      committed: ['Imported', 'تم الاستيراد', '已导入'],
      failed: ['Failed', 'فشل', '失败'],
    }),
  };
}
